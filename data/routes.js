export const ALL_KTX_STATIONS = [...new Set(KTX_ROUTES.flatMap(r => r.stops.map(s => s.name)))].sort((a,b)=>a.localeCompare(b,'ko'));

export function findKtxCandidates(fromName, toName) {
  return KTX_ROUTES.filter(route => {
    const a = route.stops.findIndex(s => s.name === fromName);
    const b = route.stops.findIndex(s => s.name === toName);
    return a >= 0 && b >= 0 && a !== b;
  }).sort((r1, r2) => {
    const d1 = Math.abs(r1.stops.findIndex(s=>s.name===fromName)-r1.stops.findIndex(s=>s.name===toName));
    const d2 = Math.abs(r2.stops.findIndex(s=>s.name===fromName)-r2.stops.findIndex(s=>s.name===toName));
    return d1-d2;
  });
}
